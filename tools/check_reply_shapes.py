#!/usr/bin/env python3
"""Emit the caller/callee reply-shape inventory for the composition review.

This is a report generator, not a proof. It extracts `Contract!("arm", …, *ret)` call sites
and the next `match ret` patterns so a reviewer can compare them with the callee. The
curated `audit/composition/interfaces.yaml` is the normative table.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEPLOY = ROOT / "contracts" / "src" / "deploy"
OUT = ROOT / "audit" / "composition" / "reply-shapes.md"
CALL = re.compile(r"([A-Za-z_]\w*)\s*!\s*\(\s*@?\"([^\"]+)\"")
MATCH = re.compile(r"match\s+@?\w+\s*\{([^}]*)\}", re.S)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)

    rows: list[tuple[str, int, str, str, str]] = []
    for path in sorted(DEPLOY.glob("*.rho")):
        lines = path.read_text().splitlines()
        text = "\n".join(lines)
        for match in CALL.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            after = text[match.end():match.end() + 1200]
            pattern = MATCH.search(after)
            shape = " ".join(pattern.group(1).split()) if pattern else "(no nearby match)"
            rows.append((path.name, line, match.group(1), match.group(2), shape))

    if args.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        body = ["# Reply-shape inventory", "",
                "Generated by `tools/check_reply_shapes.py --write`; review against",
                "`interfaces.yaml`. A missing match is a composition risk, not proof of a bug.",
                "", "| File | Line | Callee | Arm | Nearby match |", "|---|---|---|---|---|"]
        for name, line, callee, arm, shape in rows:
            body.append(f"| {name} | {line} | {callee} | {arm} | `{shape}` |")
        OUT.write_text("\n".join(body) + "\n")
        print(f"reply-shapes: wrote {len(rows)} call site(s) to {OUT.relative_to(ROOT)}")
        return 0

    for name, line, callee, arm, shape in rows:
        if shape == "(no nearby match)":
            print(f"reply-shapes: {name}:{line}: {callee}@\"{arm}\" has no nearby match",
                  file=sys.stderr)
    print(f"reply-shapes: {len(rows)} call site(s); run --write to refresh the table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
